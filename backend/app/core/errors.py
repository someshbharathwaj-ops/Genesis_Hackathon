"""Standard error models and RFC 7807 Problem Details handling."""

from datetime import UTC, datetime
from typing import Any

from fastapi import HTTPException, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException


class ProblemDetails(BaseModel):
    """RFC 7807 compliant problem details envelope."""

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type",
    )
    title: str = Field(description="Short human-readable summary of the problem")
    status: int = Field(description="HTTP status code generated by origin server")
    detail: str = Field(description="Human-readable explanation specific to this occurrence")
    instance: str | None = Field(
        default=None,
        description="URI reference that identifies the specific occurrence of the problem",
    )
    code: str = Field(
        default="INTERNAL_ERROR",
        description="Machine-readable application error code",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="UTC timestamp of the error occurrence",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="Field validation error breakdown if applicable",
    )


class RecallException(Exception):
    """Base application domain exception with deterministic error metadata."""

    def __init__(
        self,
        status_code: int,
        code: str,
        title: str,
        detail: str,
        type_uri: str | None = None,
        invalid_params: list[dict[str, Any]] | None = None,
    ):
        super().__init__(detail)
        self.status_code = status_code
        self.code = code
        self.title = title
        self.detail = detail
        self.type_uri = type_uri or f"https://recall.edu/errors/{code}"
        self.invalid_params = invalid_params


class ResourceNotFoundError(RecallException):
    def __init__(self, resource: str, identifier: str):
        super().__init__(
            status_code=status.HTTP_404_NOT_FOUND,
            code="RESOURCE_NOT_FOUND",
            title="Resource Not Found",
            detail=f"{resource} identified by '{identifier}' was not found.",
        )


class AssessmentLockoutError(RecallException):
    """Raised when free-form AI tutor is queried during an active scored assessment."""

    def __init__(self, student_id: str, assessment_id: str):
        super().__init__(
            status_code=status.HTTP_403_FORBIDDEN,
            code="ASSESSMENT_LOCKOUT",
            title="AI Tutor Lockout Active",
            detail=(
                f"Free-form AI tutor assistance is disabled for student '{student_id}' "
                f"while scored assessment '{assessment_id}' is in progress."
            ),
        )


class IdempotencyConflictError(RecallException):
    """Raised when an idempotency key is reused with mismatched payloads."""

    def __init__(self, key: str):
        super().__init__(
            status_code=status.HTTP_409_CONFLICT,
            code="IDEMPOTENCY_CONFLICT",
            title="Idempotency Key Conflict",
            detail=f"Idempotency key '{key}' was already used with different payload parameters.",
        )


class InsufficientGroundingError(RecallException):
    """Raised when retrieval does not meet confidence threshold for citation."""

    def __init__(self, query: str):
        super().__init__(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            code="UNVERIFIED_EVIDENCE",
            title="Insufficient Curriculum Evidence",
            detail=(
                f"No verified curriculum materials could sufficiently ground the query: '{query}'. "
                "System abstained from answering to prevent hallucination."
            ),
        )


async def recall_exception_handler(request: Request, exc: RecallException) -> JSONResponse:
    problem = ProblemDetails(
        type=exc.type_uri,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        instance=str(request.url.path),
        code=exc.code,
        invalid_params=exc.invalid_params,
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        headers={"Content-Type": "application/problem+json"},
    )


async def validation_exception_handler(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    invalid_params = []
    for err in exc.errors():
        invalid_params.append(
            {
                "name": ".".join(str(loc) for loc in err["loc"]),
                "reason": err["msg"],
                "type": err["type"],
            }
        )

    problem = ProblemDetails(
        type="https://recall.edu/errors/VALIDATION_ERROR",
        title="Request Validation Failed",
        status=status.HTTP_422_UNPROCESSABLE_ENTITY,
        detail="The request payload contains invalid fields or violated schema constraints.",
        instance=str(request.url.path),
        code="VALIDATION_ERROR",
        invalid_params=invalid_params,
    )
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=problem.model_dump(exclude_none=True),
        headers={"Content-Type": "application/problem+json"},
    )


async def http_exception_handler(
    request: Request, exc: HTTPException | StarletteHTTPException
) -> JSONResponse:
    problem = ProblemDetails(
        type="https://recall.edu/errors/HTTP_ERROR",
        title="HTTP Error",
        status=exc.status_code,
        detail=str(exc.detail),
        instance=str(request.url.path),
        code="HTTP_ERROR",
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        headers={"Content-Type": "application/problem+json"},
    )
